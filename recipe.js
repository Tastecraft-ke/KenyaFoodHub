/* =========================================
   LOAD SELECTED RECIPE
========================================= */

const urlParams = new URLSearchParams(window.location.search);
const foodName = urlParams.get("food");

const recipe = recipes[foodName];

if (recipe) {

    document.title = recipe.title + " | Kenya Food Hub";

    document.getElementById("recipe-title").textContent =
        recipe.title;

    document.getElementById("recipe-image").src =
        recipe.image;

    document.getElementById("recipe-image").alt =
        recipe.title;

    document.getElementById("recipe-description").textContent =
        recipe.description;

    document.getElementById("prep-time").textContent =
        recipe.prepTime;

    document.getElementById("cook-time").textContent =
        recipe.cookTime;

    document.getElementById("servings").textContent =
        recipe.servings;

    document.getElementById("nutrition").textContent =
        recipe.nutrition;

    document.getElementById("benefits").textContent =
        recipe.benefits;

    document.getElementById("precautions").textContent =
        recipe.precautions;


    /* =========================================
       INGREDIENTS
    ========================================= */

    const ingredientsList =
        document.getElementById("ingredients");

    ingredientsList.innerHTML = "";

    recipe.ingredients.forEach(ingredient => {

        const li = document.createElement("li");

        li.textContent = ingredient;

        ingredientsList.appendChild(li);

    });


    /* =========================================
       COOKING INSTRUCTIONS
    ========================================= */

    const instructionsList =
        document.getElementById("instructions");

    instructionsList.innerHTML = "";

    recipe.instructions.forEach(instruction => {

        const li = document.createElement("li");

        li.textContent = instruction;

        instructionsList.appendChild(li);

    });


    /* =========================================
       BLURRED BACKGROUND
    ========================================= */

    const background =
        document.getElementById("recipe-background");

    background.style.backgroundImage =
        `url("${recipe.image}")`;

} else {

    document.getElementById("recipe-title").textContent =
        "Recipe Not Found";

    document.getElementById("recipe-description").textContent =
        "The selected recipe could not be found. Please return to the recipes page and choose a meal.";

}
